import type { ComfortContactId, ComfortOption } from '../types/comfort';

/** 一个暗线 beat：某天早晨落在常用手机上的一条"必须被听完"的消息。 */
export interface ComfortStoryBeat {
  id: string;
  /** 锚定日（早晨 runComfortMorning 派发）。 */
  day: number;
  /** 谁发来的：妈 / 阿凯 / 无联系人（她刷到的消息，sys 叙事卡）。 */
  from: ComfortContactId | 'sys';
  /** 卡片小注（"1条语音"级别的显示文案）。 */
  note: string;
  /** 对方的话（可 ｜ 连发，引擎拆气泡）。 */
  lines: string[];
  /** 她的回应选项（无选项 = 听完即收束）。 */
  options?: ComfortOption[];
  /** 听完之后的叙事行（落舒适圈日志，不耗 RNG）。 */
  narration?: string;
  /** 派发条件：any = 总是；bf_normal = 阿凯还在；bf_gone = 已分手/被抓。 */
  when?: 'any' | 'bf_normal' | 'bf_gone';
  /** 派发后要写进 ComfortState 的标记（阿凯崩坏分支用）。 */
  effect?: 'kai_arrested';
}

