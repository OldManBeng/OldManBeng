/**
 * v4.1.2 主动要钱——「今天」名单下的直接开口入口。
 *
 * 背景：以前的每一笔钱都由剧情链节点引导触发（c_li_8 之类）。玩家没有
 * 「我现在就想开口」的手。这个入口补上：金额自选（10-1000）、理由自选。
 *
 * 文案纪律（与 ASK_COST_NARRATOR 同源）：
 *  - 理由是"她的困境"——房租、医药费、话术式的心疼自己。不出现任何
 *    可复用的实操细节（没有账号/渠道/步骤，只有一句人话）。
 *  - 每个理由带两版话术：撒出去的（她说出口的）和他听到的（结果行）。
 *  - 后果明码标价：绕开剧情预热直接开口，比链上开口贵——警惕涨得多、
 *    信任掉得多；不熟的人开口大概率翻车。这是生意里最差的一种开口。
 */

/** 金额档（10 → 1000）。越大的数，翻车的代价越重（引擎按档加警惕）。 */
export const DIRECT_ASK_AMOUNTS = [10, 30, 50, 100, 200, 300, 500, 800, 1000] as const;

export interface DirectAskReason {
  id: string;
  /** 她发出去的那句话（带金额占位 {n}）。 */
  say: string;
  /** 事由标签（UI 上的一行说明）。 */
  label: string;
  /** 相对狠度 0-1：越贴近"急用救命"，他越难拒绝，但翻车后的警惕越重。 */
  weight: number;
}

