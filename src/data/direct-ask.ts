/**
 * v4.1.2 主动要钱——「今天」名单老头卡片上的直接开口入口。
 *
 * 背景：以前的每一笔钱都由剧情链节点引导触发（c_li_8 之类）。玩家没有
 * 「我现在就想开口」的手。这个入口补上：金额自选（10-1000）、理由自选，
 * 并且走的是一场真正的对话（和「陪他说说话」同一套聊天界面）——
 * 他先打招呼 → 她把要钱的话发出去 → 他答复（成/不成两版）→ 她还有
 * 一轮追问的选择权。开口不是发一条冷冰冰的请求，是当面看着他反应。
 *
 * 文案纪律（与 ASK_COST_NARRATOR 同源）：
 *  - 理由是"她的困境"——房租、医药费、话术式的心疼自己。不出现任何
 *    可复用的实操细节（没有账号/渠道/步骤，只有一句人话）。
 *  - 每个理由带两版话术：撒出去的（她说出口的）和他听到的（结果行）。
 *  - 后果明码标价：绕开剧情预热直接开口，比链上开口贵——警惕涨得多、
 *    信任掉得多；不熟的人开口大概率翻车。这是生意里最差的一种开口。
 *  - 翻车后的追问选项更贵：软磨硬泡再失败，他就开始算了（警惕大涨）。
 */

